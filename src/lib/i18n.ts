const DICTS: Record<Locale, Dict> = { en, fa };

export function t(locale: Locale, key: string): string {
  return DICTS[locale]?.[key] ?? DICTS.en[key] ?? key;
}

export function makeT(locale: Locale) {
  return (key: string) => t(locale, key);
}

export const CURRENCIES: Record<string, { symbol: string; name: string; nameFa: string }> = {
  EUR: { symbol: "€", name: "Euro", nameFa: "یورو" },
  USD: { symbol: "$", name: "US Dollar", nameFa: "دلار آمریکا" },
  IRR: { symbol: "تومان", name: "Iranian Toman", nameFa: "تومان" },
  AED: { symbol: "د.إ", name: "UAE Dirham", nameFa: "درهم امارات" },
  GBP: { symbol: "£", name: "British Pound", nameFa: "پوند انگلیس" },
  TRY: { symbol: "₺", name: "Turkish Lira", nameFa: "لیر ترکیه" },
  CAD: { symbol: "C$", name: "Canadian Dollar", nameFa: "دلار کانادا" },
  AUD: { symbol: "A$", name: "Australian Dollar", nameFa: "دلار استرالیا" },
};

export function formatPrice(amount: number, currency: string, locale: Locale): string {
  const cur = CURRENCIES[currency] ?? CURRENCIES.EUR;
  const formatted = new Intl.NumberFormat(locale === "fa" ? "fa-IR" : "en-US", {
    minimumFractionDigits: amount % 1 === 0 ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(amount);
  if (currency === "IRR") return `${formatted} ${cur.symbol}`;
  return `${cur.symbol}${formatted}`;
}
